public class TypeCasting {
    public static void main(String[] args) {

        double d = 15.75;
        int i = (int)d;

        int x = 25;
        double y = (double)x;

        System.out.println("Double Value = " + d);
        System.out.println("Converted Int = " + i);

        System.out.println("Integer Value = " + x);
        System.out.println("Converted Double = " + y);
    }
}